import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import fs from "fs";
import path from "path";

// [ID 1.0] esbuild 번들러 및 로컬 테스트 볼트 자동 배포 설정
// -> 오프라인 한국 공휴일/음력 라이브러리는 번들에 내장하고, 옵시디언 런타임 제공 모듈은 external 처리함.
const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Calendar Memo Plugin for Obsidian
*/
`;

const prod = process.argv[2] === "production";

// [ID 1.0.1] 테스트 볼트 플러그인 폴더 자동 동기화
// -> 개인 로컬 볼트 경로를 코드에 하드코딩하지 않고 환경변수 또는 로컬 .env(OBSIDIAN_VAULT_PATH)에서 읽어 동기화함.
const PLUGIN_ID = "calendar-memo";

function resolveTestVaultPath() {
  if (process.env.OBSIDIAN_VAULT_PATH) {
    return process.env.OBSIDIAN_VAULT_PATH.trim();
  }
  const envFile = path.resolve(".env");
  if (!fs.existsSync(envFile)) return "";
  const lines = fs.readFileSync(envFile, "utf8").split(/\r?\n/);
  for (const line of lines) {
    const match = line.match(/^\s*OBSIDIAN_VAULT_PATH\s*=\s*(.+)\s*$/);
    if (match) {
      return match[1].trim().replace(/^["']|["']$/g, "");
    }
  }
  return "";
}

function deployToTestVault() {
  try {
    const vaultPath = resolveTestVaultPath();
    if (!vaultPath || !fs.existsSync(vaultPath)) {
      return;
    }
    const pluginDir = path.join(vaultPath, ".obsidian", "plugins", PLUGIN_ID);
    fs.mkdirSync(pluginDir, { recursive: true });
    for (const file of ["main.js", "manifest.json", "styles.css"]) {
      const src = path.resolve(file);
      if (fs.existsSync(src)) {
        fs.copyFileSync(src, path.join(pluginDir, file));
      }
    }
    console.log(`[calendar-memo] Synced build artifacts to ${pluginDir}`);
  } catch (err) {
    console.warn("[calendar-memo] Failed to sync to test vault:", err);
  }
}

const syncPlugin = {
  name: "sync-to-obsidian-vault",
  setup(build) {
    build.onEnd((result) => {
      if (result.errors.length === 0) {
        deployToTestVault();
      }
    });
  },
};

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins,
  ],
  format: "cjs",
  target: "es2020",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  plugins: [syncPlugin],
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}

